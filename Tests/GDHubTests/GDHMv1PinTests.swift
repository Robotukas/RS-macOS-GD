import XCTest
import CryptoKit
import GDHubXlate
@testable import GDHub

/// Pins what the GDHM v1 encoder writes today (remap step 2, slice S1(b)), so the later slices (the model with six more
/// remappable controls, GDHM v2, the encoder's version choice) can prove they keep today's bytes. Committed before any
/// of those changes, from the code as it was.
///
/// What is pinned (`Fixtures/gdhm-v1-pins.json`):
/// - the factory mapping's blob (revisions 1 and 42), and the learned sets A and B of `GDHubDefaults.h`;
/// - the blob (SHA-256 and length) of 200 seeded remapped mappings that v1 can say, some with stray learned bits on the
///   analog triggers, and a hash of each mapping so a drifting generator is told apart from a changed encoder;
/// - `remapLimit` (the step-1 messages) for 300 seeded mappings, refused ones included.
/// The step-1 messages are also written out as literals below.
///
/// `GDHUB_RECORD_GDHM_PINS=1 swift test --filter GDHMv1PinTests` rewrites the fixture. Never do that to make a failing
/// run pass: a difference here means a v1 byte moved.
final class GDHMv1PinTests: XCTestCase {
    typealias F = XlateFixtures

    private static let fixtureURL = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
        .appendingPathComponent("Fixtures/gdhm-v1-pins.json")

    // MARK: Generators (frozen: a seed must keep giving the same mapping)

    private static let pinnedCount = 200
    private static let limitCount = 300

    /// 200 remapped mappings v1 can say: default, live-shaped or random learned base, random expressible remaps, every
    /// fourth with stray learned bits on `lt` and `rt`.
    static func pinnedMappings() -> [ControlMapping] {
        var rng = SplitMix64(seed: 0x9141_0000)
        var out: [ControlMapping] = []
        for i in 0..<pinnedCount {
            let base = [ControlMapping.default, F.liveShaped, F.randomMapping(&rng)][i % 3]
            var m = F.randomOutputs(base, 0x91AB_0000 + UInt64(i))
            if i % 4 == 3 { m = F.withStrayTriggerBits(m, 0x57A4_0000 + UInt64(i)) }
            out.append(m)
        }
        return out
    }

    /// 300 mappings for the `remapLimit` messages, refused ones included (the seeds `MapBlobEncoderTests` uses).
    static func limitMappings() -> [ControlMapping] {
        (0..<limitCount).map { i in
            F.randomOutputs(i % 2 == 0 ? ControlMapping.default : F.liveShaped, 0xA11C_E000 + UInt64(i), expressibleOnly: false)
        }
    }

    // MARK: Encoding

    private static func encode(_ m: ControlMapping, revision: UInt32 = 1) -> [UInt8]? {
        if case .blob(let b) = MapBlobEncoder.encode(m, identity: F.identity, spec: F.spec, revision: revision) { return b }
        return nil
    }

    private static func sha(_ bytes: [UInt8]) -> String {
        SHA256.hash(data: Data(bytes)).map { String(format: "%02x", $0) }.joined()
    }

    private static func hexString(_ bytes: [UInt8]) -> String { bytes.map { String(format: "%02x", $0) }.joined() }

    /// The whole fixture as it would be written now.
    private static func current() throws -> [String: Any] {
        var root: [String: Any] = [:]
        root["about"] = "GDHM v1 bytes of the encoder as of remap step 2, slice S1(b). Generated by GDHMv1PinTests; a difference means a v1 byte moved."
        root["pad"] = "xbox-bt16, default pad spec"
        root["factoryRevision1"] = hexString(try XCTUnwrap(encode(.default, revision: 1)))
        root["factoryRevision42"] = hexString(try XCTUnwrap(encode(.default, revision: 42)))
        root["learnedA"] = hexString(try XCTUnwrap(encode(GDHubXlateGoldenTests.learnedA)))
        root["learnedB"] = hexString(try XCTUnwrap(encode(GDHubXlateGoldenTests.learnedB)))
        root["remapped"] = try pinnedMappings().enumerated().map { i, m -> [String: Any] in
            let b = try XCTUnwrap(encode(m, revision: UInt32(i + 1)), "pinned mapping \(i) must encode")
            return ["i": i, "mappingHash": DevRunReportStore.mappingHash(m), "length": b.count, "blobSHA256": sha(b)]
        }
        root["remapLimits"] = limitMappings().enumerated().map { i, m -> [String: Any] in
            ["i": i, "mappingHash": DevRunReportStore.mappingHash(m), "limit": MapBlobEncoder.remapLimit(m) ?? NSNull()]
        }
        return root
    }

    private func fixture() throws -> [String: Any] {
        if ProcessInfo.processInfo.environment["GDHUB_RECORD_GDHM_PINS"] == "1" {
            let data = try JSONSerialization.data(withJSONObject: try Self.current(), options: [.prettyPrinted, .sortedKeys])
            try (data + Data("\n".utf8)).write(to: Self.fixtureURL)
        }
        let data = try Data(contentsOf: Self.fixtureURL)
        return try XCTUnwrap(try JSONSerialization.jsonObject(with: data) as? [String: Any])
    }

    // MARK: Tests

    func testFactoryAndLearnedBlobsArePinned() throws {
        let f = try fixture()
        XCTAssertEqual(Self.hexString(try XCTUnwrap(Self.encode(.default, revision: 1))), f["factoryRevision1"] as? String)
        XCTAssertEqual(Self.hexString(try XCTUnwrap(Self.encode(.default, revision: 42))), f["factoryRevision42"] as? String)
        XCTAssertEqual(Self.hexString(try XCTUnwrap(Self.encode(GDHubXlateGoldenTests.learnedA))), f["learnedA"] as? String)
        XCTAssertEqual(Self.hexString(try XCTUnwrap(Self.encode(GDHubXlateGoldenTests.learnedB))), f["learnedB"] as? String)
        // The same bytes the checked-in defaults header carries.
        XCTAssertEqual(try XCTUnwrap(Self.encode(.default, revision: 1)), GDHubXlateGoldenTests.factoryBlob)
        XCTAssertEqual((f["factoryRevision1"] as? String)?.count, 2 * 408, "the factory blob is 408 bytes")
    }

    func testTwoHundredRemappedMappingsEncodeToTheirPinnedBytes() throws {
        let pins = try XCTUnwrap(try fixture()["remapped"] as? [[String: Any]])
        let mappings = Self.pinnedMappings()
        XCTAssertEqual(pins.count, Self.pinnedCount)
        XCTAssertEqual(mappings.count, Self.pinnedCount)
        var remapped = 0, stray = 0
        for (i, m) in mappings.enumerated() {
            let pin = pins[i]
            XCTAssertEqual(pin["i"] as? Int, i)
            XCTAssertEqual(DevRunReportStore.mappingHash(m), pin["mappingHash"] as? String, "mapping \(i): the generator drifted, not the encoder")
            let b = try XCTUnwrap(Self.encode(m, revision: UInt32(i + 1)), "mapping \(i) encodes")
            XCTAssertEqual(F.validate(b), GDX_OK, "mapping \(i)")
            XCTAssertEqual(UInt16(b[4]) | UInt16(b[5]) << 8, 1, "mapping \(i) is version 1")
            XCTAssertEqual(b.count, pin["length"] as? Int, "mapping \(i)")
            XCTAssertEqual(Self.sha(b), pin["blobSHA256"] as? String, "mapping \(i): v1 bytes moved")
            if !m.outputs.isEmpty { remapped += 1 }
            if m.physicalBits["lt"] != nil || m.physicalBits["rt"] != nil { stray += 1 }
        }
        XCTAssertGreaterThan(remapped, 170, "the draw really remaps")
        XCTAssertGreaterThan(mappings.filter { $0.physicalBits["lt"] != nil && $0.outputs["lt"] != nil }.count + stray, 20)
    }

    func testStep1RemapLimitMessagesArePinned() throws {
        let pins = try XCTUnwrap(try fixture()["remapLimits"] as? [[String: Any]])
        let mappings = Self.limitMappings()
        XCTAssertEqual(pins.count, Self.limitCount)
        var kinds = Set<String>(), refused = 0
        for (i, m) in mappings.enumerated() {
            XCTAssertEqual(DevRunReportStore.mappingHash(m), pins[i]["mappingHash"] as? String, "mapping \(i): the generator drifted")
            let got = MapBlobEncoder.remapLimit(m)
            XCTAssertEqual(got, pins[i]["limit"] as? String, "mapping \(i)")
            if let why = got {
                refused += 1
                for kind in ["buttons send", "cannot pull a trigger", "controls send"] where why.contains(kind) { kinds.insert(kind) }
            }
        }
        XCTAssertGreaterThan(refused, 30)
        XCTAssertEqual(kinds.count, 3, "all three step-1 kinds are in the pinned set: \(kinds)")
    }

    func testStep1RemapLimitMessagesAreWrittenOut() {
        func m(_ picks: [(String, ControlOutput)]) -> ControlMapping {
            var x = ControlMapping.default
            for (id, o) in picks { x.setOutput(o, for: id) }
            return x
        }
        XCTAssertNil(MapBlobEncoder.remapLimit(.default))
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("g1", .pad(.y)), ("g2", .pad(.y))])), "three buttons send Y: y, g1, g2")
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("g1", .pad(.dpad_up)), ("g2", .pad(.dpad_up)), ("g3", .pad(.dpad_up))])),
                       "four buttons send D-pad up: dpad_up, g1, g2, g3")
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("g1", .pad(.lt))])), "g1 sends LT: a button cannot pull a trigger in this driver version")
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("g5", .pad(.rt))])), "g5 sends RT: a button cannot pull a trigger in this driver version")
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("lt", .pad(.rt))])), "two controls send RT: rt, lt")
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("rt", .pad(.lt))])), "two controls send LT: lt, rt")
        XCTAssertEqual(MapBlobEncoder.remapLimit(m([("start", .pad(.y)), ("g1", .pad(.y))])), "three buttons send Y: y, start, g1")
        XCTAssertNil(MapBlobEncoder.remapLimit(m([("lt", .pad(.rt)), ("rt", .pad(.lt))])))
    }

    /// A default mapping with `physicalBits` on `lt` and `rt` is the default blob: the bits of a control that sends no
    /// pad button are never read, and `triggerFeed` keeps its binding (`.analog`). Swapped triggers likewise keep their
    /// analog fields.
    func testStrayBitsOnTheTriggersLeaveTheFactoryBlobAlone() throws {
        var m = ControlMapping.default
        m.physicalBits["lt"] = 1
        m.physicalBits["rt"] = 0x20
        let factory = try XCTUnwrap(Self.encode(.default))
        XCTAssertEqual(Self.encode(m), factory)
        XCTAssertEqual(try MapBlobEncoder.table(m, identity: F.identity, spec: F.spec, revision: 1).triggers,
                       [.init(item: 20, field: 0), .init(item: 21, field: 1)])
        var swapped = ControlMapping.default
        swapped.setOutput(.pad(.rt), for: "lt"); swapped.setOutput(.pad(.lt), for: "rt")
        var swappedStray = swapped
        swappedStray.physicalBits["lt"] = 1; swappedStray.physicalBits["rt"] = 0x20
        XCTAssertEqual(Self.encode(swappedStray), Self.encode(swapped), "triggers stay analog, bits unread")
        XCTAssertEqual(try MapBlobEncoder.table(swappedStray, identity: F.identity, spec: F.spec, revision: 1).triggers,
                       [.init(item: 20, field: 1), .init(item: 21, field: 0)])
    }

    /// The frozen id list is today's `remappableIDs`, so the generator keeps its draw while the live list grows.
    func testTheFrozenIdListIsStepOnesRemappableList() {
        XCTAssertEqual(F.frozenRemappableIDs.count, 23)
        XCTAssertEqual(Set(F.frozenRemappableIDs).count, 23)
        XCTAssertTrue(F.frozenRemappableIDs.allSatisfy { ControlMapping.remappableIDs.contains($0) })
        XCTAssertEqual(Array(ControlMapping.remappableIDs.prefix(23)), F.frozenRemappableIDs, "new ids are appended, never inserted")
    }

    /// The Swift mapper and the C core agree on the pinned mappings with stray trigger bits (a sample of frames).
    func testStrayTriggerBitMappingsStillMatchTheSwiftOracle() throws {
        var rng = SplitMix64(seed: 0x57A4_F00D)
        for (i, m) in Self.pinnedMappings().enumerated() where i % 4 == 3 && i < 60 {
            let core = try F.core(m)
            let oracle = SwiftOracle(mapping: m)
            let log = MismatchLog()
            for _ in 0..<300 {
                let raw = F.randomRaw(&rng)
                guard let want = oracle.state(raw) else { continue }
                guard let got = core.eval(raw: raw) else { log.note("mapping \(i): C rejected \(hex(raw))"); continue }
                if core.reports(got) != oracle.reports(want) || XlateCore.state(from: got) != want { log.note("mapping \(i): \(hex(raw))") }
            }
            log.assertNone("stray trigger bits, mapping \(i)")
        }
    }
}
