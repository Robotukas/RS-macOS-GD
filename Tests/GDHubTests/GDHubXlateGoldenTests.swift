import XCTest
import GDHubXlate
@testable import GDHub

/// `Shared/GDHubDefaults.h` is generated here: the constants both sides agree on, the factory GDHM blob, the default
/// pad spec and 64 golden vectors `{frame[16], out01[16], out02[2]}`. The vectors' expected bytes come from the Swift
/// pipeline (the oracle), never from the C core. The same vectors run inside the dext as its self-test (plan 6.5).
///
/// Regenerate after an intended change: `GDHUB_REGEN_DEFAULTS=1 swift test --filter GDHubXlateGoldenTests`.
final class GDHubXlateGoldenTests: XCTestCase {
    typealias F = XlateFixtures

    static let revision: UInt32 = 1

    static var factoryBlob: [UInt8] {
        guard case .blob(let b) = MapBlobEncoder.encode(.default, identity: .xboxBT16_02E0, spec: F.spec, revision: revision) else { fatalError("factory mapping must encode") }
        return b
    }

    /// 64 frames: 40 hand-picked (idle, every button, every hat value, stick and trigger extremes, the deadband and the
    /// no-range quirk) then 24 from a fixed-seed generator.
    static var goldenFrames: [[UInt8]] {
        var out: [[UInt8]] = []
        func frame(_ f: (inout [UInt8]) -> Void = { _ in }) {
            var b = [UInt8](repeating: 0, count: 16); b[0] = 6; F.setTriggers(&b, 0, 0, hat: 8)
            f(&b); out.append(b)
        }
        func axes(_ x: Int, _ y: Int, _ z: Int, _ rz: Int) -> (inout [UInt8]) -> Void {
            { b in for (i, v) in [x, y, z, rz].enumerated() {
                let u = UInt16(bitPattern: Int16(v)); b[1 + 2 * i] = UInt8(u & 0xff); b[2 + 2 * i] = UInt8(u >> 8) } }
        }
        frame()                                                                                    // idle
        for bit in 0..<19 { frame { F.setButtons(&$0, 1 << bit, extra: 0) } }                      // 1...19
        for hat in 0..<8 { frame { F.setTriggers(&$0, 0, 0, hat: hat) } }                          // N...NW
        frame(axes(32767, 32767, 32767, 32767)); frame(axes(-32768, -32768, -32768, -32768))
        frame(axes(100, -100, 100, -100)); frame(axes(65, -65, 66, -66)); frame(axes(1, -1, 0, 0))
        frame { F.setTriggers(&$0, 1023, 1023, hat: 8) }; frame { F.setTriggers(&$0, 2, 3, hat: 8) }
        frame { F.setTriggers(&$0, 512, 100, hat: 8) }
        frame(axes(16000, -16000, 20000, -20000))
        frame { F.setButtons(&$0, 0x7ffff, extra: 0x1fff); F.setTriggers(&$0, 1023, 1023, hat: 1) }  // everything
        var rng = SplitMix64(seed: 0x601D_E4)
        while out.count < 64 { out.append(F.randomRaw(&rng)) }
        return out
    }

    static func goldenVectors() -> [[UInt8]] {
        let oracle = SwiftOracle(mapping: .default, identity: .xboxBT16_02E0)
        return goldenFrames.map { raw in
            let r = oracle.reports(oracle.state(raw)!)
            return raw + r[0].bytes + r[1].bytes
        }
    }

    static func headerText() -> String {
        func block(_ name: String, _ bytes: [UInt8]) -> String {
            var s = "static const uint8_t \(name)[\(bytes.count)] = {\n"
            for row in stride(from: 0, to: bytes.count, by: 16) {
                s += "    " + bytes[row..<min(row + 16, bytes.count)].map { String(format: "0x%02X", $0) }.joined(separator: ", ") + ",\n"
            }
            return s + "};\n"
        }
        let blob = factoryBlob
        let vectors = goldenVectors()
        var s = """
        #ifndef GDHubDefaults_h
        #define GDHubDefaults_h
        /*
         * GENERATED by Tests/GDHubTests/GDHubXlateGoldenTests.swift. Do not edit: the test fails when this file differs from
         * what the Swift encoder and the Swift oracle produce. Regenerate with
         *   GDHUB_REGEN_DEFAULTS=1 swift test --filter GDHubXlateGoldenTests
         *
         * What both sides (app and driver) must agree on: the constants, the factory GDHM v1 blob (ControlMapping.default on
         * the pad identity "xbox-bt16-02e0"), the pad spec it targets, and golden vectors whose expected bytes come from the
         * Swift pipeline (GamepadFrame.parse -> PassthroughPadMapper -> snapped -> PadReportBuilders.xboxBT16).
         */
        #include <stdint.h>

        #define GDX_DEFAULT_PAD_IDENTITY        "xbox-bt16-02e0"
        #define GDX_DEFAULT_REVISION            \(revision)u
        #define GDX_DEFAULT_SILENCE_NEUTRAL_MS  250
        #define GDX_DEFAULT_DEADBAND            0.002
        #define GDX_DEFAULT_HYSTERESIS          0.002
        #define GDX_DEFAULT_STICK_ACTIVE        0.5
        #define GDX_DEFAULT_TRIGGER_ACTIVE_RAW  100
        #define GDX_DEFAULT_AXIS_ACTIVE_RAW     16000
        #define GDX_DEFAULT_BLOB_LEN            \(blob.count)
        #define GDX_DEFAULT_SPEC_LEN            \(F.spec.count)
        #define GDX_GOLDEN_COUNT                \(vectors.count)
        #define GDX_GOLDEN_STRIDE               34      /* frame[16], report 0x01 [16], report 0x02 [2] */


        """
        s += block("GDX_DEFAULT_BLOB", blob) + "\n"
        s += block("GDX_DEFAULT_SPEC", F.spec) + "\n"
        s += block("GDX_GOLDEN", vectors.flatMap { $0 })
        s += "\n#endif\n"
        return s
    }

    private var headerURL: URL {
        URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Shared/GDHubDefaults.h")
    }

    func testCheckedInHeaderMatchesTheGenerator() throws {
        let want = Self.headerText()
        if ProcessInfo.processInfo.environment["GDHUB_REGEN_DEFAULTS"] == "1" {
            try want.write(to: headerURL, atomically: true, encoding: .utf8)
            print("regenerated \(headerURL.path)")
        }
        let have = try String(contentsOf: headerURL, encoding: .utf8)
        XCTAssertTrue(have == want, "Shared/GDHubDefaults.h differs from the generator output; run with GDHUB_REGEN_DEFAULTS=1 and review the diff")
    }

    func testConstantsAgreeWithTheSwiftSide() {
        let t = GDHMTable()
        XCTAssertEqual(GDX_DEFAULT_DEADBAND, t.deadband)
        XCTAssertEqual(GDX_DEFAULT_HYSTERESIS, t.hysteresis)
        XCTAssertEqual(GDX_DEFAULT_STICK_ACTIVE, t.stickActive)
        XCTAssertEqual(Int32(GDX_DEFAULT_TRIGGER_ACTIVE_RAW), t.triggerActiveRaw)
        XCTAssertEqual(Int32(GDX_DEFAULT_AXIS_ACTIVE_RAW), t.axisActiveRaw)
        XCTAssertEqual(UInt16(GDX_DEFAULT_SILENCE_NEUTRAL_MS), t.silenceNeutralMs)
        XCTAssertEqual(Int(GDX_SILENCE_NEUTRAL_MS), 250)
        let c = VirtualPadSink.Config()
        XCTAssertEqual(c.axisDeadband, GDX_DEFAULT_DEADBAND)
        XCTAssertEqual(c.triggerDeadband, GDX_DEFAULT_DEADBAND)
        XCTAssertEqual(Int(GDX_DEFAULT_BLOB_LEN), Self.factoryBlob.count)
        XCTAssertEqual(Int(GDX_DEFAULT_SPEC_LEN), F.spec.count)
        XCTAssertEqual(PadIdentity.xboxBT16_02E0.id, "xbox-bt16-02e0")
        XCTAssertEqual(PadIdentity.default.id, "xbox-bt16-02e0")
    }

    /// The compiled-in blob and spec come back out of the C header intact and validate; the 64 vectors run through the
    /// SwiftPM C target give exactly the Swift oracle's bytes.
    func testGoldenVectorsThroughTheCCore() throws {
        let blob = withUnsafeBytes(of: GDX_DEFAULT_BLOB) { Array($0) }
        let spec = withUnsafeBytes(of: GDX_DEFAULT_SPEC) { Array($0) }
        let golden = withUnsafeBytes(of: GDX_GOLDEN) { Array($0) }
        XCTAssertEqual(blob, Self.factoryBlob)
        XCTAssertEqual(spec, F.spec)
        XCTAssertEqual(F.validate(blob, spec: spec), GDX_OK)
        let core = try XlateCore(blob: blob, spec: spec)
        XCTAssertEqual(golden.count, Int(GDX_GOLDEN_COUNT) * Int(GDX_GOLDEN_STRIDE))
        for v in 0..<Int(GDX_GOLDEN_COUNT) {
            let at = v * Int(GDX_GOLDEN_STRIDE)
            let frame = Array(golden[at..<at + 16]), r1 = Array(golden[at + 16..<at + 32]), r2 = Array(golden[at + 32..<at + 34])
            let reports = core.reports(try XCTUnwrap(core.eval(raw: frame)))
            XCTAssertEqual(reports.map(\.bytes), [r1, r2], "vector \(v): \(hex(frame))")
            // and through gdx_step on a fresh state, which posts both reports for the first frame
            var m = core.map; var st = gdx_state(); var out = gdx_out()
            let mask = frame.withUnsafeBufferPointer { gdx_step(&st, &m, $0.baseAddress, 16, &out) }
            if mask != 0 { XCTAssertEqual(mask, 3, "vector \(v)"); XCTAssertEqual(XlateCore.reports(out).map(\.bytes), [r1, r2]) }
        }
    }

    func testTheVectorsCoverTheInterestingCases() {
        let v = Self.goldenVectors()
        XCTAssertEqual(v.count, 64)
        XCTAssertEqual(Set(v.map { Array($0[0..<16]) }).count, 64, "no duplicate frames")
        XCTAssertTrue(v.contains { $0[16 + 14] != 0 }, "some buttons")
        XCTAssertTrue(v.contains { $0[32 + 1] == 1 }, "Guide")
        XCTAssertEqual(Set(v.map { $0[16 + 13] }).count, 9, "all hat values 0...8")
        XCTAssertTrue(v.contains { $0[16 + 1] == 0 && $0[16 + 2] == 0 }, "stick at the negative stop")
    }
}
